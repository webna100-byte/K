// Builds public/js/icons.js: only the Lucide icons the site uses, inlined,
// so pages don't download the whole icon library from a CDN.
// Usage: npm pack lucide-static@0.453.0 && tar xzf lucide-static-0.453.0.tgz
//        node scripts/build-icons.mjs <path-to>/package/icons
import fs from 'node:fs';
import path from 'node:path';

const ICONS = [
  'award', 'gift', 'house', 'bell', 'bell-off', 'bell-plus', 'bell-ring', 'receipt-text', 'bike', 'check', 'flame', 'lock', 'lock-keyhole',
  'log-in', 'log-out', 'mail', 'map-pin', 'menu', 'phone', 'refresh-ccw', 'send', 'shield-check', 'shopping-bag', 'shopping-cart',
  'smartphone', 'sparkles', 'star', 'x', 'store', 'images', 'layout-grid', 'utensils', 'truck', 'palette', 'settings', 'panel-bottom',
  'key-round', 'file-text', 'percent', 'users', 'printer', 'trash-2', 'clock', 'volume-2', 'wifi-off', 'download', 'upload', 'database',
  'chef-hat', 'plus', 'minus', 'external-link', 'refresh-cw', 'filter', 'circle-check', 'circle-x', 'megaphone', 'badge-percent', 'user'
];

const dir = process.argv[2];
const out = {};
for (const name of ICONS) {
  const svg = fs.readFileSync(path.join(dir, name + '.svg'), 'utf8');
  out[name] = svg.replace(/<!--[\s\S]*?-->/g, '').match(/<svg[^>]*>([\s\S]*)<\/svg>/)[1].replace(/\s*\n\s*/g, '');
}
const js = `/* Generated by scripts/build-icons.mjs from lucide-static@0.453.0 (ISC). */
(function () {
  var I = ${JSON.stringify(out)};
  function createIcons() {
    document.querySelectorAll('i[data-lucide]:not([data-done])').forEach(function (el) {
      var name = el.getAttribute('data-lucide'), body = I[name];
      if (!body) return;
      el.setAttribute('data-done', '');
      el.setAttribute('aria-hidden', 'true');
      el.innerHTML = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">' + body + '</svg>';
    });
  }
  window.lucide = { createIcons: createIcons };
})();
`;
fs.writeFileSync(new URL('../public/js/icons.js', import.meta.url), js);
console.log('icons:', ICONS.length, 'bytes:', js.length);
